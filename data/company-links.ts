const aliases = companyLinks.flatMap(({ names, url }) => names.map((name) => ({ name, url })))
  .sort((a, b) => b.name.length - a.name.length);
const escape = (text: string) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const pattern = `(?<![\\p{L}\\p{N}_])(?:${aliases.map(({ name }) => escape(name)).join("|")})(?![\\p{L}\\p{N}_])`;
const destinations = new Map(aliases.map(({ name, url }) => [name.toLowerCase(), url]));

export function officialCompanyUrl(name: string) {
  return destinations.get(name.trim().toLowerCase());
}

export function splitCompanyMentions(text: string): Array<{ text: string; url?: string }> {
  const result: Array<{ text: string; url?: string }> = [];
  let cursor = 0;
  for (const match of text.matchAll(new RegExp(pattern, "giu"))) {
    if (match.index > cursor) result.push({ text: text.slice(cursor, match.index) });
    const ambiguous = ["wise", "notion", "meta", "slack"].includes(match[0].toLowerCase());
    const exactCase = aliases.some(({ name }) => name === match[0]);
    result.push({ text: match[0], url: !ambiguous || exactCase ? destinations.get(match[0].toLowerCase()) : undefined });
    cursor = match.index + match[0].length;
  }
  if (cursor < text.length) result.push({ text: text.slice(cursor) });
  return result;
}
